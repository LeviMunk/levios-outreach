import assert from 'node:assert/strict';
import {candidate} from './discover-jobs.mjs';
import {validateMixed} from './validate-jobos-pack.mjs';
const stamp=new Date().toISOString().slice(0,10);
const base={company:'Example Employer',title:'Marketing Operations Analyst',url:'https://job-boards.greenhouse.io/example/jobs/1234567',body:'$80,000 - $95,000. We hire anywhere in the United States.'};
const local=candidate({...base,location:'Appleton, WI'},stamp);
assert.ok(local,'Verified Appleton record should qualify');
assert.equal(local.locationBucket,'local20');
assert.ok(validateMixed({records:[local],strategies:[]}).valid,'Local record must pass server-like research validation');
assert.equal(candidate({...base,location:'Green Bay, WI'},stamp),null,'Outside Appleton radius cannot qualify as local');
const remote=candidate({...base,location:'Remote - US'},stamp);
assert.ok(remote,'Remote role with explicit US-wide eligibility should qualify');
assert.equal(remote.remoteWisconsinEligible,'yes');
assert.equal(candidate({...base,location:'Remote - US',body:'$80,000 - $95,000'},stamp),null,'Unverified remote eligibility must not qualify');
assert.equal(candidate({...base,location:'Appleton, WI',url:'https://untrusted.test/jobs/123'},stamp),null,'Non-employer-hosted source must not qualify');
assert.equal(candidate({...base,location:'Appleton, WI',title:'Sales Representative'},stamp),null,'Irrelevant role must not qualify');
assert.equal(validateMixed({records:[{...local,draft:'Please contact me'}]}).valid,false,'Intake cannot accept prefilled outbound messages');
assert.equal(validateMixed({records:[{...local,locationBucket:'remote',distanceMiles:'',remoteWisconsinEligible:''}]}).valid,false,'Remote Wisconsin eligibility required');
console.log('JobOS job discovery and intake validation: 9 checks passed.');
